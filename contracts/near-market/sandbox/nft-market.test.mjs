import test from 'node:test';
import assert from 'node:assert/strict';
import {Worker} from 'near-workspaces';
const unit=10n**24n, gas='250000000000000', one='1';
test('NEP178 sale locks exact approval; real NFT failure refunds buyer and failed FT withdrawal restores credit',async()=>{
 const worker=await Worker.init();try{
  const root=worker.rootAccount, a={};
  for(const n of ['token','market','passport','fox','seller','buyer','other'])a[n]=await root.createSubAccount(n);
  const {token,market,passport,fox,seller,buyer,other}=a;
  await passport.deploy('/wasm/near_passport.wasm');await token.deploy('/wasm/sandbox_mock_ft.wasm');await market.deploy('/wasm/near_market.wasm');await fox.deploy('/wasm/near_fox.wasm');
  await root.call(token,'new',{owner_id:root.accountId,supply:String(1000n*unit)});
  await root.call(fox,'new',{owner_id:root.accountId});
  await root.call(passport,'new',{owner_id:root.accountId,collection_id:fox.accountId,network:'near-testnet',career_signer_id:root.accountId});
  await root.call(market,'new',{owner_id:root.accountId,foxo_contract_id:token.accountId,nft_contract_id:fox.accountId,passport_contract_id:passport.accountId});
  for(const acct of [market,buyer])await root.call(token,'storage_deposit',{account_id:acct.accountId},{attachedDeposit:String(unit/10n)});
  await root.call(token,'ft_transfer',{receiver_id:buyer.accountId,amount:'100000'},{attachedDeposit:one});
  for(const acct of [seller,buyer,other])await acct.call(market,'fund_account',{}, {attachedDeposit:String(unit/10n)});
  const block=await root.provider.block({finality:'final'}),expiry=String(BigInt(block.header.timestamp_nanosec)+3600n*1000000000n);
  const list=async(id)=>{
   await root.call(fox,'nft_mint',{token_id:id,receiver_id:seller.accountId,token_metadata:{title:'Fox',media:'https://example.com/fox.png',media_hash:Buffer.alloc(32).toString('base64'),copies:1}},{attachedDeposit:String(unit/10n)});
   await seller.call(market,'fund_listing',{token_id:id},{attachedDeposit:String(unit/10n)});
   await seller.call(fox,'nft_approve',{token_id:id,account_id:market.accountId,msg:JSON.stringify({price_atomic:'10001',expires_at_ns:expiry,career_revision:'0'})},{attachedDeposit:String(unit/10n),gas});
   return market.view('get_listing',{token_id:id});
  };
  const prepare=(id,pid,l)=>buyer.call(market,'prepare_purchase',{purchase_id:pid,token_id:id,approval_id:l.approval_id,price_atomic:l.price_atomic,career_revision:l.career_revision},{attachedDeposit:String(unit/10n)});
  const pay=(pid,amount='10001')=>buyer.call(token,'ft_transfer_call',{receiver_id:market.accountId,amount,msg:JSON.stringify({purchase_id:pid})},{attachedDeposit:one,gas});
  let l=await list('001');
  assert.equal((await fox.view('nft_token',{token_id:'001'})).owner_id,seller.accountId);
  await prepare('001','buy-1',l);
  await assert.rejects(buyer.call(market,'nft_on_approve',{token_id:'001',owner_id:seller.accountId,approval_id:99,msg:'{}'}),/collection/);
  await root.call(market,'set_enabled',{enabled:true});
  await pay('buy-1','10000');assert.equal((await market.view('get_purchase',{purchase_id:'buy-1'})).status,'prepared');
  await pay('buy-1');
  assert.equal((await fox.view('nft_token',{token_id:'001'})).owner_id,buyer.accountId);
  assert.equal((await market.view('get_purchase',{purchase_id:'buy-1'})).status,'delivered');
  assert.equal(await market.view('get_credit',{account_id:seller.accountId}),'9751');
  assert.deepEqual(await market.view('get_ledger'),{principal:'0',credits:'9751',fees:'250',withdraw_pending:'0'});
  await pay('buy-1');assert.equal(await token.view('ft_balance_of',{account_id:buyer.accountId}),'89999');
  await seller.call(market,'withdraw_credit',{}, {attachedDeposit:one,gas});
  assert.equal(await market.view('get_credit',{account_id:seller.accountId}),'9751');
  await root.call(token,'storage_deposit',{account_id:seller.accountId},{attachedDeposit:String(unit/10n)});
  await seller.call(market,'withdraw_credit',{}, {attachedDeposit:one,gas});
  assert.equal(await token.view('ft_balance_of',{account_id:seller.accountId}),'9751');
  l=await list('002');await prepare('002','buy-fail',l);
  await seller.call(fox,'nft_revoke',{token_id:'002',account_id:market.accountId},{attachedDeposit:one});
  await pay('buy-fail');
  assert.equal((await market.view('get_purchase',{purchase_id:'buy-fail'})).status,'refundable');
  assert.equal(await market.view('get_credit',{account_id:buyer.accountId}),'10001');
  assert.equal((await market.view('get_ledger')).fees,'250');
  await buyer.call(market,'withdraw_credit',{}, {attachedDeposit:one,gas});
  assert.equal(await token.view('ft_balance_of',{account_id:buyer.accountId}),'89999');
  await pay('unknown');assert.equal(await token.view('ft_balance_of',{account_id:buyer.accountId}),'89999');
  await assert.rejects(buyer.call(market,'resolve_purchase',{purchase_id:'buy-1'},{gas}),/private/);
  l=await list('003');await prepare('003','moved',l);
  await seller.call(fox,'nft_transfer',{receiver_id:other.accountId,token_id:'003'},{attachedDeposit:one});
  await pay('moved');assert.equal((await market.view('get_purchase',{purchase_id:'moved'})).status,'refundable');
  assert.equal((await fox.view('nft_token',{token_id:'003'})).owner_id,other.accountId);
 }finally{await worker.tearDown();}
});
